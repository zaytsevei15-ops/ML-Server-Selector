"""UI smoke tests against the already running Expo web preview, not an APK build."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parent
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 390, 'height': 844})
    errors, requests, passed = [], [], []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: requests.append(r.url + ' ' + (r.post_data or '')))
    page.goto('http://localhost:4300', wait_until='networkidle', timeout=120000)
    expect(page.get_by_text('Прежде чем начать', exact=True)).to_be_visible(timeout=60000)
    expect(page.get_by_role('button', name='Понятно, продолжить', exact=True)).to_be_disabled()
    page.get_by_role('checkbox').click()
    page.get_by_role('button', name='Понятно, продолжить', exact=True).click()
    expect(page.get_by_text('Прежде чем начать', exact=True)).to_be_hidden()
    passed.append('Mandatory first-run warning and acknowledgment')
    expect(page.get_by_text('совместимых профилей', exact=False).first).to_be_visible(timeout=60000)
    assert any('/api/rpc/vpnGate/list' in r for r in requests)
    page.screenshot(path=str(ROOT / 'countries-dark.png'))
    page.get_by_label('Поиск страны или города').fill('Казань')
    expect(page.get_by_role('button', name='Россия', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Германия', exact=True)).to_have_count(0)
    page.get_by_role('button', name='Россия', exact=True).click()
    expect(page.get_by_role('radio', name='Казань', exact=True)).to_be_checked()
    for name in ['Москва', 'Санкт-Петербург', 'Казань', 'Екатеринбург', 'Новосибирск']:
        expect(page.get_by_role('radio', name=name, exact=True)).to_be_visible()
    expect(page.get_by_role('radio', name='Владивосток', exact=True)).to_be_visible()
    page.get_by_label('Поиск города в России').fill('Калининград')
    expect(page.get_by_role('radio', name='Калининград', exact=True)).to_be_visible()
    expect(page.get_by_role('radio', name='Москва', exact=True)).to_have_count(0)
    page.get_by_label('Поиск города в России').fill('')
    page.get_by_role('button', name='Сохранить направление', exact=True).click()
    expect(page.get_by_text('Направление сохранено.', exact=True)).to_be_visible()
    saved = page.evaluate("JSON.parse(sessionStorage.getItem('ml-selector-preferences-v1'))")
    assert saved['destinationId'] == 'ru-kazan' and saved['consentVersion'] == 4
    expect(page.get_by_role('button', name='Подключение недоступно', exact=True)).to_be_disabled()
    expect(page.get_by_role('button', name='Измерить пинг', exact=True)).to_be_disabled()
    expect(page.get_by_text('Пинг с телефона', exact=True)).to_be_visible()
    profile_button = page.get_by_role('button', name='Проверить профиль', exact=True)
    if profile_button.is_enabled():
        profile_button.click()
        expect(page.get_by_text('Структура профиля проверена', exact=True)).to_be_visible(timeout=60000)
        passed.append('Live Russian profile structural check, never a connected state')
    else:
        passed.append('Russia has no current compatible profiles; connection stays disabled')
    page.screenshot(path=str(ROOT / 'country-detail.png'))
    passed.append('Live feed, Russia city search, destination persistence, honest tunnel blocker')
    page.get_by_role('button', name='Все страны', exact=True).click()
    page.get_by_label('Поиск страны или города').fill('Япония')
    expect(page.get_by_role('button', name='Япония', exact=True)).to_be_visible(timeout=60000)
    page.get_by_role('button', name='Япония', exact=True).click()
    expect(page.get_by_text('Город неизвестен', exact=True).first).to_be_visible()
    page.get_by_role('button', name='Все страны', exact=True).click()
    page.get_by_role('tab', name='Мой сервер').click()
    field = page.get_by_label('ID игрока и сервера')
    field.fill('bad')
    page.get_by_role('button', name='Проверить ID', exact=True).click()
    expect(page.get_by_text('Проверьте формат ID', exact=True)).to_be_visible()
    field.fill('987654321 (5678)')
    page.get_by_role('button', name='Проверить ID', exact=True).click()
    expect(page.get_by_text('Регион: достоверно не определён', exact=True)).to_be_visible()
    page.screenshot(path=str(ROOT / 'id-check.png'))
    passed.append('Invalid/valid ID format and explicit unknown region')
    page.get_by_role('tab', name='Настройки').click()
    page.get_by_role('button', name='Светлая', exact=True).click()
    page.get_by_role('button', name='English', exact=True).click()
    expect(page.get_by_text('Settings', exact=True).first).to_be_visible()
    page.screenshot(path=str(ROOT / 'settings-light-en.png'))
    page.reload(wait_until='networkidle')
    expect(page.get_by_text('Settings', exact=True).first).to_be_visible()
    saved = page.evaluate("JSON.parse(sessionStorage.getItem('ml-selector-preferences-v1'))")
    assert saved['theme'] == 'light' and saved['language'] == 'en' and saved['consent'] is True
    expect(page.get_by_text('Before you begin', exact=True)).to_have_count(0)
    passed.append('Language/theme persistence across reload, consent persistence')
    page.get_by_role('tab', name='Countries').click()
    page.get_by_text('Advanced Server', exact=True).click()
    expect(page.get_by_text('Test server', exact=True)).to_be_visible()
    passed.append('Advanced Server informational route')
    page.get_by_role('button', name='All countries', exact=True).click()
    page.route('**/api/rpc/vpnGate/list**', lambda route: route.abort())
    page.get_by_role('button', name='Refresh VPN Gate', exact=True).click()
    expect(page.get_by_text('Источник недоступен. Список не актуален.', exact=True).or_(page.get_by_text('Source unavailable. List is not current.', exact=True))).to_be_visible(timeout=15000)
    page.screenshot(path=str(ROOT / 'source-unavailable.png'))
    passed.append('Source failure shown explicitly; no invented availability')
    assert not any('987654321' in request for request in requests), 'ID leaked into request'
    assert not errors, errors
    passed.append('No entered ID in observed requests; no JS runtime errors')
    (ROOT / 'results.json').write_text(json.dumps({'passed': passed, 'runtime_errors': errors, 'request_count': len(requests), 'scope': 'Chrome Expo web preview; native device and cloud APK not tested'}, ensure_ascii=False, indent=2))
    print(json.dumps(passed, ensure_ascii=False, indent=2))
    browser.close()